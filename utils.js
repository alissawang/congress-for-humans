
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function categorizeText(text) {
  const t = text.toLowerCase();
  for (const rule of CATEGORY_RULES) {
    if (rule.keywords.some((k) => t.includes(k))) return rule.name;
  }
  return DEFAULT_CATEGORY;
}

function ordinal(n) {
  const v = n % 100;
  if (v >= 11 && v <= 13) return `${n}th`;
  switch (n % 10) {
    case 1:
      return `${n}st`;
    case 2:
      return `${n}nd`;
    case 3:
      return `${n}rd`;
    default:
      return `${n}th`;
  }
}

function parseDate(value) {
  if (!value) return null;
  const d = new Date(value);
  return Number.isNaN(d.getTime()) ? null : d;
}

function billText(bill) {
  if (!bill || typeof bill !== "object") return "";
  const title = bill.title || "";
  const description = bill.description || "";
  const summary = bill.summary && typeof bill.summary === "object" ? bill.summary.text || "" : "";
  return `${title} ${description} ${summary}`.trim();
}

function makePrimaryName(bill) {
  const title = typeof bill?.title === "string" ? bill.title.trim() : "";
  const description = typeof bill?.description === "string" ? bill.description.trim() : "";
  const summary = bill?.summary && typeof bill.summary === "object" ? String(bill.summary.text || "").trim() : "";

  if (!title && !description && !summary) return "Untitled bill";

  const raw = title || description || summary;
  let candidate = raw.replace(/^(a bill to|a joint resolution to|a resolution to)\s+/i, "to ");
  candidate = candidate.replace(/\s+/g, " ").trim();

  return candidate[0].toUpperCase() + candidate.slice(1);
}

function makeSecondaryName(bill, primary) {
  const description = typeof bill?.description === "string" ? bill.description.trim() : "";
  if (description && description !== primary) return description;
  const title = typeof bill?.title === "string" ? bill.title.trim() : "";
  if (title && title !== primary) return title;
  return "";
}

function formatMonthYear(date) {
  return `${MONTHS[date.getMonth()]} ${date.getFullYear()}`;
}

function congressLabel(congress) {
  return congress ? `${ordinal(congress)} Congress` : "Unknown congress";
}

function yearTickLabel(minDate, maxDate) {
  if (!minDate) return "Year";
  const start = minDate.getFullYear();
  const end = maxDate ? maxDate.getFullYear() : start;
  return start === end ? String(start) : `${start}\u2013${String(end).slice(-2)}`;
}

function durationMonths(minDate, maxDate) {
  if (!minDate || !maxDate) return 1;
  const start = minDate.getFullYear() * 12 + minDate.getMonth();
  const end = maxDate.getFullYear() * 12 + maxDate.getMonth();
  return Math.max(1, end - start + 1);
}

function coerceList(x) {
  if (!x) return [];
  if (Array.isArray(x)) return x;
  if (typeof x === "object") {
    for (const k of ["items", "results", "sponsoredLegislation"]) {
      if (Array.isArray(x[k])) return x[k];
    }
  }
  return [];
}

function groupBillsByCategory(bills) {
  const groups = new Map();
  for (const b of bills) {
    const text = billText(b);
    if (!text) continue;
    const category = categorizeText(text);
    if (!groups.has(category)) groups.set(category, []);
    groups.get(category).push(b);
  }
  return Array.from(groups, ([category, billsForCategory]) => ({
    category,
    count: billsForCategory.length,
    bills: billsForCategory,
  })).sort((a, b) => b.count - a.count);
}

function groupBillsByCongress(bills) {
  const sessions = new Map();

  for (const b of bills) {
    const congress = Number(b?.congress) || null;
    const key = `${congress || "x"}`;
    const introduced = parseDate(b?.introducedDate);

    if (!sessions.has(key)) {
      sessions.set(key, {
        key,
        congress,
        bills: [],
        minDate: null,
        maxDate: null,
      });
    }

    const entry = sessions.get(key);
    entry.bills.push(b);
    if (introduced) {
      entry.minDate = entry.minDate ? new Date(Math.min(entry.minDate, introduced)) : introduced;
      entry.maxDate = entry.maxDate ? new Date(Math.max(entry.maxDate, introduced)) : introduced;
    }
  }

  return Array.from(sessions.values())
    .map((s) => {
      let range = null;
      if (s.minDate && s.maxDate) {
        const start = formatMonthYear(s.minDate);
        const end = formatMonthYear(s.maxDate);
        range = start === end ? start : `${start}\u2013${end}`;
      }
      return { ...s, range, label: congressLabel(s.congress) };
    })
    .sort((a, b) => {
      return (b.congress || 0) - (a.congress || 0);
    });
}

