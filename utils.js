function pixelArtPositions(base, scale) {
  // A procedural base has no cells to blow up - ask it for the finished size.
  if (base.procedural) return base.draw(base.h * scale, base.w * scale);

  const out = [];
  for (let r = 0; r < base.length; r++) {
    for (let c = 0; c < base[r].length; c++) {
      if (base[r][c]) {
        for (let dr = 0; dr < scale; dr++) {
          for (let dc = 0; dc < scale; dc++) {
            out.push({ row: r * scale + dr, col: c * scale + dc });
          }
        }
      }
    }
  }
  return out;
}

// A base that draws itself at whatever resolution it is asked for, rather than
// being resampled from a bitmap. `h` and `w` are its natural proportions, which
// is all fitShapeToCount needs in order to pick a grid. `fit` is optional: a
// shape that has some slack in it can implement one to land nearer an exact cell
// count than a whole-number grid size alone can manage.
function proceduralShape(h, w, draw, fit) {
  return { procedural: true, h, w, draw, fit };
}

const baseHeight = (base) => (base.procedural ? base.h : base.length);
const baseWidth = (base) =>
  base.procedural ? base.w : Math.max(...base.map((r) => r.length));

// Nearest-neighbour resample of a base shape onto a rows x cols grid.
//
// Each output cell takes the source cell under its CENTRE, not under its leading
// corner. Corner sampling biases every lookup toward low indices, which quietly
// breaks mirror symmetry the moment rows != H: a disc came out a cell wider on
// the right than the left down most of its height. Centre sampling is exactly
// antisymmetric, so a symmetric base stays symmetric at every resolution.
function resampleShape(base, rows, cols) {
  if (base.procedural) return base.draw(rows, cols);

  const H = base.length;
  const W = baseWidth(base);
  const out = [];
  for (let r = 0; r < rows; r++) {
    const sr = Math.min(H - 1, Math.floor(((r + 0.5) * H) / rows));
    for (let c = 0; c < cols; c++) {
      const sc = Math.min(W - 1, Math.floor(((c + 0.5) * W) / cols));
      if (base[sr][sc]) out.push({ row: r, col: c });
    }
  }
  return out;
}

// Find the resolution at which the shape lights up just enough cells to give every
// bill its own cell, so one lit cell stands for exactly one bill. Integer scaling
// can only step 1x, 4x, 9x... which overshoots badly; resampling at a fractional
// scale lets the shape land near the bill count.
//
// We take the smallest resolution that COVERS the count rather than the largest
// that fits under it: no bill goes unrepresented, and the surplus cells just stay
// blank at the tail of the shape. A shape with a `fit` keeps that surplus small,
// so the blank tail is a nick in the last row rather than a missing cap.
function fitShapeToCount(base, target) {
  const H = baseHeight(base);
  const W = baseWidth(base);
  const lit = base.procedural
    ? base.draw(H, W).length
    : base.flat().filter(Boolean).length;
  if (!lit || target <= 0) return { positions: [], rows: H, cols: W };

  let best = null;
  let lo = 0.05;
  let hi = Math.max(1, Math.sqrt(target / lit) * 2 + 2);

  for (let i = 0; i < 60; i++) {
    const k = (lo + hi) / 2;
    const rows = Math.max(1, Math.round(H * k));
    const cols = Math.max(1, Math.round(W * k));
    const positions = resampleShape(base, rows, cols);
    if (positions.length >= target) {
      if (!best || positions.length < best.positions.length) best = { positions, rows, cols };
      hi = k;
    } else {
      lo = k;
    }
  }

  // Never collapse to nothing: fall back to the shape at 1:1.
  if (!best) best = { positions: resampleShape(base, H, W), rows: H, cols: W };

  // Let a shape that can flex take the surplus itself.
  if (base.procedural && base.fit) {
    const fitted = base.fit(best.rows, best.cols, target);
    if (fitted.length >= target && fitted.length < best.positions.length) {
      best = { ...best, positions: fitted };
    }
  }
  return best;
}

