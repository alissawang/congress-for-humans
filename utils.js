// An equals sign inside a ring. Alone among the icons this one is not a fixed
// bitmap, because a circle is the one shape that shows resampling error at a
// glance. fitShapeToCount has to redraw every base at whatever resolution the
// bill count calls for, and nearest-neighbour blowing up a 15x15 disc duplicates
// source rows unevenly: the rim ends up with one- and two-cell steps in an order
// set by the resample ratio rather than by the curve, which reads as lumps. A
// procedural base draws straight onto the target grid, so there is no source
// bitmap to degrade and every resolution gets a true disc.
//
// The proportions are the ones the hand-drawn 15x15 version had, written as
// fractions of its outer radius so the icon still looks like itself. At 15x15
// this reproduces that drawing cell for cell.
const CIVIL_RIGHTS_R = 7.5;                      // radius of the original, in cells
const CIVIL_RIGHTS_HOLE = 4.5 / CIVIL_RIGHTS_R;  // inner edge of the ring
const CIVIL_RIGHTS_BAR_MID = 1 / CIVIL_RIGHTS_R; // how far each bar sits off centre
const CIVIL_RIGHTS_BAR_HALF = 0.5 / CIVIL_RIGHTS_R;  // half a bar's thickness
const CIVIL_RIGHTS_BAR_REACH = 3.5 / CIVIL_RIGHTS_R; // how far the bars run

function drawEqualityRing(rows, cols, hole = CIVIL_RIGHTS_HOLE) {
  const out = [];
  for (let r = 0; r < rows; r++) {
    const dy = (r + 0.5 - rows / 2) / (rows / 2);
    for (let c = 0; c < cols; c++) {
      const dx = (c + 0.5 - cols / 2) / (cols / 2);
      const d = Math.hypot(dx, dy);
      const ring = d <= 1 && d >= hole;
      const bar =
        Math.abs(dx) <= CIVIL_RIGHTS_BAR_REACH &&
        Math.abs(Math.abs(dy) - CIVIL_RIGHTS_BAR_MID) <= CIVIL_RIGHTS_BAR_HALF;
      if (ring || bar) out.push({ row: r, col: c });
    }
  }
  return out;
}

// Grid sizes are whole numbers, so the smallest grid that covers a bill count
// usually overshoots it - by as much as 50 cells. That surplus stays blank at the
// tail of the shape, which on a circle means the bottom of the rim goes missing.
//
// So the ring absorbs the surplus by getting slightly thinner instead, which
// brings the overshoot down to at most 15 cells and leaves the blank tail a nick
// in the last row. The outer radius never moves, which is what the eye actually
// reads, and the widest the hole ever has to open is a few percent - far below
// the point where anyone would notice the ring's weight change between one
// category and the next.
function fitEqualityRing(rows, cols, target) {
  const thinnest = 1 - 2 / rows; // keep at least ~1 cell of ring
  let lo = CIVIL_RIGHTS_HOLE;
  let hi = Math.max(CIVIL_RIGHTS_HOLE, thinnest);
  let best = drawEqualityRing(rows, cols);

  for (let i = 0; i < 40; i++) {
    const hole = (lo + hi) / 2;
    const cells = drawEqualityRing(rows, cols, hole);
    if (cells.length >= target) {
      if (cells.length < best.length) best = cells;
      lo = hole;
    } else {
      hi = hole;
    }
  }
  return best;
}

