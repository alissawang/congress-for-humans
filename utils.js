function pixelArtPositions(base, scale) {
  const out = [];
  for (let r = 0; r < base.length; r++) {
    for (let c = 0; c < base[r].length; c++) {
      if (base[r][c]) {
        for (let dr = 0; dr < scale; dr++) {
          for (let dc = 0; dc < scale; dc++) {
            out.push({ row: r * scale + dr, col: c * scale + dc });
          }
        }
      }
    }
  }
  return out;
}

